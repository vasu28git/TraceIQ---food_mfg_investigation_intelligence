-- Final investigation result – authoritative investigator conclusion (Step 20)
CREATE TABLE IF NOT EXISTS investigation_final_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id BIGINT NOT NULL REFERENCES organisations(org_id) ON DELETE CASCADE,
    investigation_id BIGINT NOT NULL REFERENCES investigation(id) ON DELETE CASCADE,
    outcome TEXT NOT NULL CHECK (outcome <> ''),
    conclusion TEXT NOT NULL CHECK (conclusion <> ''),
    rationale TEXT,
    created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_final_outcome_length CHECK (char_length(outcome) <= 100),
    CONSTRAINT chk_final_conclusion_length CHECK (char_length(conclusion) <= 10000),
    CONSTRAINT chk_final_rationale_length CHECK (char_length(rationale) <= 10000),
    CONSTRAINT uq_final_result_org_investigation UNIQUE (org_id, investigation_id)
);
CREATE INDEX IF NOT EXISTS idx_final_result_org_investigation ON investigation_final_result(org_id, investigation_id);
CREATE INDEX IF NOT EXISTS idx_final_result_org_created ON investigation_final_result(org_id, created_at);
